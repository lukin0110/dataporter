def test_no_chunk_exceeds_the_budget(export_dir: Path, attachments_dir: Path) -> None:
    for outcome in seeds_of(export_dir, attachments_dir, 4_000).values():
        if outcome.seed is None:
            continue
        assert all(len(chunk.text) <= 4_000 for chunk in outcome.seed.chunks)


def body_count(text: str) -> int:
    """How many message fragments a part carries.

    A part is `opening`, the fragments, then the footer, joined by the separator,
    so there is always one more separator than there are fragments.
    """
    return text.count(f"\n\n{render.SEPARATOR}\n\n") - 1


def test_the_only_over_budget_chunk_holds_one_indivisible_fragment(
    tmp_path: Path,
) -> None:
    """`04` allows exactly one exception, and this is what forces it: a budget so
    small that the envelope alone spends it, leaving a part that is one fragment
    and still too long. Anything with a second fragment in it could have been
    split further and is a bug."""
    # The hard cap is lifted out of the way: this is about the per-part budget,
    # and 300-character parts spend most of themselves on envelopes.
    settings = Settings(
        workspace=tmp_path,
        seed=SeedSettings(max_chars=300, hard_max_chars=1_000_000),
    )
    outcome = seeding.SeedGenerator(settings).seed(one_turn("z" * 2_000))
    assert outcome.seed is not None

    over = [chunk for chunk in outcome.seed.chunks if len(chunk.text) > 300]
    assert over, "the exception is meant to be reachable; this asserts nothing if not"
    for chunk in over:
        assert body_count(chunk.text) == 1
        # A fragment is not a message, so no part claims it as delivered.
        assert chunk.message_uuids == []


