@pytest.mark.parametrize("max_chars", [50_000, 4_000], ids=["default", "4000"])
def test_every_chunk_ends_with_its_acknowledgement_line(
    export_dir: Path, attachments_dir: Path, max_chars: int
) -> None:
    for outcome in seeds_of(export_dir, attachments_dir, max_chars).values():
        if outcome.seed is None:
            continue
        total = len(outcome.seed.chunks)
        for position, chunk in enumerate(outcome.seed.chunks, start=1):
            expected = f"MIGRATION-ACK {outcome.short_id} {position}/{total}"
            assert chunk.ack == expected
            assert chunk.text.endswith(f"{expected}\n")
            assert (chunk.index, chunk.total) == (position, total)


def test_sha256_of_is_sha256_over_utf8_bytes() -> None:
    """The digest is `orval.hashify`'s now, and `08` compares it against what a
    browser composer holds — so pin it to the definition rather than trust it.

    Non-ASCII on purpose: any encoding but UTF-8 would agree on plain text and
    part ways exactly where a real conversation does.
    """
    text = "Grüße, 世界\n---\nMIGRATION-ACK\n"
    assert seeding.sha256_of(text) == hashlib.sha256(text.encode("utf-8")).hexdigest()


def test_every_sha256_is_the_hash_of_its_own_text(
    export_dir: Path, attachments_dir: Path
) -> None:
    seed = seed_of(export_dir, attachments_dir, LONG, max_chars=4_000)
    for chunk in seed.chunks:
        assert chunk.sha256 == seeding.sha256_of(chunk.text)
    # Distinct parts hash differently: a copy-paste of the first would pass a
    # weaker check and send part one twice.
    assert len({chunk.sha256 for chunk in seed.chunks}) == len(seed.chunks)


