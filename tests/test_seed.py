"""Seed generation.

`04`'s acceptance criteria are the first four sections. The golden files under
`tests/fixtures/seeds/` are the format's pin: they are regenerated by writing the
fixture export with `SeedGenerator` and reviewed as a diff, never edited by hand
to make a test pass — a change to them is a change to what a destination chat
receives.
"""

import hashlib
from pathlib import Path

import pytest
from typer.testing import CliRunner

from dataporter import cli, render
from dataporter import seed as seeding
from dataporter.config import AttachmentSettings, SeedSettings, Settings
from dataporter.exit_codes import ExitCode
from dataporter.export import load_export
from dataporter.export.model import Conversation

GOLDEN = Path(__file__).parent / "fixtures" / "seeds"

SIMPLE = "aa000001-1111-4111-8111-111111111111"
LONG = "bb000002-2222-4222-8222-222222222222"
ARTIFACT = "cc000003-3333-4333-8333-333333333333"
ATTACHMENT = "dd000004-4444-4444-8444-444444444444"
BRANCH = "ee000005-5555-4555-8555-555555555555"
EMPTY = "ff000006-6666-4666-8666-666666666666"

MIGRATABLE = [SIMPLE, LONG, ARTIFACT, ATTACHMENT, BRANCH]

OFF_PATH_TEXT = "`ferry` — short, and it carries things across."
"""The branch fixture's abandoned reply. It is never in a seed."""


def one_turn(
    text: str, uuid: str = "aaaaaaaa-1111-4111-8111-111111111111"
) -> Conversation:
    """A one-message conversation, for the rules the fixture does not exercise."""
    return Conversation.model_validate(
        {
            "uuid": uuid,
            "name": "One long turn",
            "created_at": "2024-05-01T09:00:00Z",
            "updated_at": "2024-05-01T09:00:00Z",
            "chat_messages": [
                {
                    "uuid": "m1",
                    "sender": "human",
                    "text": text,
                    "content": [],
                    "created_at": "2024-05-01T09:00:00Z",
                    "updated_at": "2024-05-01T09:00:00Z",
                }
            ],
            "current_leaf_message_uuid": "m1",
        }
    )


def settings_for(attachments_dir: Path, max_chars: int = 50_000) -> Settings:
    return Settings(
        workspace=attachments_dir.parent,
        seed=SeedSettings(max_chars=max_chars),
        attachments=AttachmentSettings(dir=attachments_dir),
    )


def seeds_of(
    export_dir: Path, attachments_dir: Path, max_chars: int = 50_000
) -> dict[str, seeding.SeedOutcome]:
    generator = seeding.SeedGenerator(settings_for(attachments_dir, max_chars))
    export = load_export(export_dir)
    return {
        outcome.conversation_uuid: outcome
        for outcome in generator.seeds(export.conversations)
    }


def seed_of(
    export_dir: Path, attachments_dir: Path, uuid: str, max_chars: int = 50_000
) -> seeding.Seed:
    outcome = seeds_of(export_dir, attachments_dir, max_chars)[uuid]
    assert outcome.seed is not None
    return outcome.seed


